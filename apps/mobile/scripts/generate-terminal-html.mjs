// Inlines xterm.js into a single HTML page for the terminal WebView, so the
// terminal works offline and without a bundler asset. Runs on `npm install`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
const read = (spec) => readFileSync(require.resolve(spec), "utf8");

const xtermJs = read("@xterm/xterm/lib/xterm.js");
const xtermCss = read("@xterm/xterm/css/xterm.css");
const fitJs = read("@xterm/addon-fit/lib/addon-fit.js");
const pageJs = readFileSync(join(here, "terminal-page.js"), "utf8");

// Keep inline scripts from terminating the <script> element early.
const inline = (js) => js.replace(/<\/script/gi, "<\\/script");

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, minimum-scale=1, maximum-scale=6, user-scalable=yes">
<style>${xtermCss}
html, body { margin: 0; padding: 0; height: 100%; background: #0A0C0F; overflow: auto; }
#terminal { padding: 4px; box-sizing: border-box; }
body.fit #terminal { height: 100%; }
.xterm .xterm-viewport { background-color: #0A0C0F !important; }
</style>
</head>
<body>
<div id="terminal"></div>
<script>${inline(xtermJs)}</script>
<script>${inline(fitJs)}</script>
<script>${inline(pageJs)}</script>
</body>
</html>`;

const out = join(here, "..", "src", "terminal", "terminal-html.generated.ts");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `// Generated by scripts/generate-terminal-html.mjs. Do not edit.\nexport const TERMINAL_HTML = ${JSON.stringify(html)};\n`);
console.log(`terminal page: ${(html.length / 1024).toFixed(0)} KiB → ${out}`);
